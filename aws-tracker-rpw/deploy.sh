#!/usr/bin/env bash
# Deploy the Retirement Planning Window seat tracker.
#
#   ./deploy.sh <SUPABASE_URL> <SUPABASE_ANON_KEY>
#
# Run setup.sql in the Supabase SQL editor FIRST. This script only writes
# config.js and deploys; it does not touch the database.
set -euo pipefail

if [ $# -ne 2 ]; then
  cat >&2 <<'USAGE'
usage: ./deploy.sh <SUPABASE_URL> <SUPABASE_ANON_KEY>

  SUPABASE_URL       e.g. https://abcdefghijklmnopqrst.supabase.co
  SUPABASE_ANON_KEY  the "anon public" key, starts with eyJ

Both are in Supabase > Project Settings > API, on the SAME project as the
July 4 / Back-to-School trackers. Run setup.sql there before deploying.
USAGE
  exit 1
fi

URL="$1"; KEY="$2"
cd "$(dirname "$0")"

case "$URL" in
  https://*.supabase.co) ;;
  *) echo "error: first argument does not look like a Supabase project URL: $URL" >&2; exit 1 ;;
esac
case "$KEY" in
  eyJ*) ;;
  *) echo "error: second argument does not look like an anon key (expected it to start with eyJ)" >&2; exit 1 ;;
esac

printf '// Generated by deploy.sh on %s\nconst SUPABASE_URL = "%s";\nconst SUPABASE_ANON_KEY = "%s";\n' \
  "$(date -u '+%Y-%m-%d %H:%M UTC')" "$URL" "$KEY" > config.js
echo "wrote config.js for ${URL}"

if ! command -v vercel >/dev/null 2>&1; then
  echo "vercel CLI not found; installing globally"
  npm install -g vercel
fi

# Link to a NEW project named aws-tracker-rpw. Do not accept a link to an
# existing project: this repo is already connected to the "mogly" Vercel
# project, and deploying into that would overwrite the Mogly app's domain.
if [ ! -f .vercel/project.json ]; then
  echo "linking to Vercel project aws-tracker-rpw"
  vercel link --yes --project aws-tracker-rpw
fi

echo "deploying to production"
vercel deploy --prod --yes
